#!/usr/bin/env python3
"""generate_cpp_data.py — 把 M3 纠错模型数据固化为 C++ 头，供原生解码用。

从 correction/ 的纯 Python 数据（全部 ASCII 拼音，无敏感文本）生成：
  - 420 音节表 + 音节先验代价表（prior）
  - 二元转移代价表（bigram_costs.json：denom[420] + trans[N]）

用途：cpp/pinyin_corrector.cpp 无 Python 依赖运行纠错，替换「行模式每行 fork
一个 Python 进程」的桥接（correction/fix_pinyin.py 仍保留作对比/评测口径）。

用法：python3 -m correction.generate_cpp_data > cpp/correction_data.h
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

# 用绝对导入，兼容 `python3 -m correction.generate_cpp_data` 与脚本直跑。
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from correction import syllables, prior  # noqa: E402

_DATA = Path(__file__).resolve().parent / "data" / "bigram_costs.json"


def main() -> int:
    syls = list(syllables.SYLLABLES)
    idx = {s: i for i, s in enumerate(syls)}
    n = len(syls)

    raw = json.loads(_DATA.read_text(encoding="utf-8"))
    meta = raw["meta"]
    smooth = float(meta["smooth"])

    # denom 并行表（按音节索引）；缺失的 prev 用平滑公式兜底（与 transition.py 一致）。
    denom_map = {k: float(v) for k, v in raw["denom"].items()}
    denom_fallback = smooth * len(raw["denom"])
    denom = [denom_map.get(s, denom_fallback) for s in syls]

    # trans 三元并行表（prev_idx, cur_idx, cost）
    prevs, curs, costs = [], [], []
    for key, val in raw["trans"].items():
        p, c = key.split("|")
        if p in idx and c in idx:
            prevs.append(idx[p])
            curs.append(idx[c])
            costs.append(float(val))
    # 按 (prev, cur) 排序，便于二进制查找 / 差分
    order = sorted(range(len(prevs)), key=lambda i: (prevs[i], curs[i]))
    prevs = [prevs[i] for i in order]
    curs = [curs[i] for i in order]
    costs = [costs[i] for i in order]

    out = []
    w = out.append
    w("// Auto-generated by correction/generate_cpp_data.py — DO NOT EDIT.")
    w("// 数据 = 420 音节 + 先验代价 + 音节二元转移代价（全部 ASCII 拼音）。")
    w("#pragma once")
    w("#include <cstdint>")
    w("")
    w("namespace pinyin_correction_data {")
    w("")
    w(f"inline constexpr int kNumSyllables = {n};")
    w(f"inline constexpr double kSmooth = {smooth!r};")
    w(f"inline constexpr double kLambda = 0.15;")
    w(f"inline constexpr double kDenomFallbackCount = {len(raw['denom'])};")
    w("")
    w("inline constexpr const char *kSyllables[] = {")
    for s in syls:
        w(f'    "{s}",')
    w("};")
    w("")
    w("inline constexpr double kSyllablePriors[] = {")
    for s in syls:
        w(f"    {prior.syllable_prior_cost(s)!r},")
    w("};")
    w("")
    w("inline constexpr double kDenom[] = {")
    for d in denom:
        w(f"    {d!r},")
    w("};")
    w("")
    w(f"inline constexpr int kNumTrans = {len(prevs)};")
    w("inline constexpr uint16_t kTransPrev[] = {")
    for v in prevs:
        w(f"    {v},")
    w("};")
    w("inline constexpr uint16_t kTransCur[] = {")
    for v in curs:
        w(f"    {v},")
    w("};")
    w("inline constexpr float kTransCost[] = {")
    for v in costs:
        w(f"    {v}f,")
    w("};")
    w("")
    w("}  // namespace pinyin_correction_data")
    w("")
    print("\n".join(out))
    print(f"// [stderr] 音节={n} trans={len(prevs)} denom={len(denom_map)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())