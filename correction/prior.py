"""音节先验（数据驱动版）。

CHIME 的排序式是「音节先验 × 信道变换概率」。信道在 channel.py；这里的先验用于
打破「同编辑代价」下的并列（如 "b" 补元音得到 ba/bi/bo/bu 全都并列时，按频度分
先后），以及给候选排序一个频度权重。

**数据来源**：中文维基百科 2000 句 + 人民网新闻 2000 句 + 日常口语 70 句 +
近期人民网新闻 4000 句（共 150,400 个汉字），用 pypinyin 转为不带声调的全拼，
统计 420 个普通话音节的出现频度（覆盖 396/420）。
未覆盖的音节用 0.5 的平滑值（拉普拉斯平滑思想），避免零概率。

**缩放设计**：
  原始 -ln(prob) 范围 3.39~11.90（跨度 8.51），远大于信道代价范围 0~1.5。
  乘以 alpha=0.035 后，先验代价范围 0.12~0.44（跨度 0.32）。
  这个跨度 **小于最小信道代价差**（confusion 0.35 ↔ phonetic 0.40 = 0.05，
  但跨编辑距离的最小差是 confusion 0.35 ↔ 2×confusion 0.70 = 0.35），
  确保先验只能做 tie-break，不能篡夺信道的主导权。

用法：syllable_prior_cost(syl) 返回「代价 = -ln 先验概率」（越小越常见）。
"""

