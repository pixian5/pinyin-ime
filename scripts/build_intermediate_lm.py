valid_bigrams = valid_bigrams[:10000]

# Create ARPA file
with open("/tmp/better7.arpa", "w", encoding="utf-8") as f:
    n1 = len(words) + 3
    n2 = len(valid_bigrams) + 2
    f.write("\\data\\\n")
    f.write(f"ngram 1={n1}\n")
    f.write(f"ngram 2={n2}\n")
    f.write("\n\\1-grams:\n")
    f.write("-99.0\t<s>\n")
    f.write("-99.0\t</s>\n")
    f.write("-99.0\t<unk>\n")
    for word, freq in words:
        prob = math.log10(freq / total_freq)
        f.write(f"{prob:.4f}\t{word}\n")
    f.write("\n\\2-grams:\n")
    if words:
        f.write(f"-0.5\t<s>\t{words[0][0]}\n")
        f.write(f"-0.3\t{words[0][0]}\t</s>\n")
    total_bigram = sum(c for _, _, c in valid_bigrams) + 1
    for w1, w2, count in valid_bigrams:
        prob = math.log10(count / total_bigram)
        f.write(f"{prob:.4f}\t{w1}\t{w2}\n")
    f.write("\n\\end\\\n")

print(f"ARPA: {len(words)} unigrams + {len(valid_bigrams)} bigrams")
